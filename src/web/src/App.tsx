import { useEffect, useState } from 'react'
import Markdown from 'react-markdown'
import { getCompanies, getReports, type CompanySummary, type Report, type Sentiment } from './api'

const sentimentLabel: Record<Sentiment, string> = {
  bullish: 'Bullish',
  neutral: 'Neutral',
  bearish: 'Bearish',
  none: 'No analyst activity',
  failed: 'Research failed',
}

const formatDate = (iso: string) =>
  new Date(iso).toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' })

function SentimentBadge({ sentiment }: { sentiment: Sentiment }) {
  return <span className={`badge ${sentiment}`}>{sentimentLabel[sentiment] ?? sentiment}</span>
}

// Web content is untrusted: react-markdown does not render raw HTML, and links open in a new tab without referrer.
function ReportBody({ markdown }: { markdown: string }) {
  return (
    <div className="markdown">
      <Markdown
        components={{
          a: ({ node: _node, ...props }) => <a {...props} target="_blank" rel="noopener noreferrer nofollow" />,
        }}
      >
        {markdown}
      </Markdown>
    </div>
  )
}

function CompanyDetail({ company }: { company: CompanySummary }) {
  const [reports, setReports] = useState<Report[] | null>(null)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    let cancelled = false
    getReports(company.ticker)
      .then((r) => !cancelled && setReports(r))
      .catch((e: Error) => !cancelled && setError(e.message))
    return () => {
      cancelled = true
    }
  }, [company.ticker])

  return (
    <section className="detail">
      <h2>
        {company.name} <span className="ticker">{company.ticker}</span>
      </h2>
      {error && <p className="error">Could not load reports: {error}</p>}
      {!reports && !error && <p className="muted">Loading…</p>}
      {reports?.length === 0 && <p className="muted">No reports yet.</p>}
      {reports?.map((r, i) => (
        <details key={r.runUtc} open={i === 0} className="report">
          <summary>
            <span>{formatDate(r.runUtc)}</span>
            <SentimentBadge sentiment={r.sentiment} />
          </summary>
          <ReportBody markdown={r.markdown} />
        </details>
      ))}
    </section>
  )
}

export default function App() {
  const [companies, setCompanies] = useState<CompanySummary[] | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [selected, setSelected] = useState<string | null>(null)

  useEffect(() => {
    getCompanies()
      .then((c) => {
        setCompanies(c)
        setSelected((s) => s ?? c[0]?.ticker ?? null)
      })
      .catch((e: Error) => setError(e.message))
  }, [])

  const company = companies?.find((c) => c.ticker === selected)

  return (
    <>
      <header>
        <h1>Stock Watch</h1>
      </header>
      <p className="disclaimer">
        Generated by an AI agent from web search results. Verify before acting; not investment advice.
      </p>
      {error && <p className="error">Could not load companies: {error}</p>}
      {!companies && !error && <p className="muted">Loading…</p>}
      {companies?.length === 0 && <p className="muted">The watchlist is empty.</p>}
      {companies && companies.length > 0 && (
        <main>
          <nav aria-label="Companies">
            {companies.map((c) => (
              <button
                key={c.ticker}
                className={c.ticker === selected ? 'company active' : 'company'}
                onClick={() => setSelected(c.ticker)}
              >
                <span>
                  <strong>{c.ticker}</strong> {c.name}
                </span>
                {c.latest ? (
                  <>
                    <SentimentBadge sentiment={c.latest.sentiment} />
                    <small className="muted">{formatDate(c.latest.runUtc)}</small>
                  </>
                ) : (
                  <small className="muted">no report yet</small>
                )}
              </button>
            ))}
          </nav>
          {company && <CompanyDetail key={company.ticker} company={company} />}
        </main>
      )}
    </>
  )
}
